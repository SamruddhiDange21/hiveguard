"""Controlled Simulation & Fault Injection Laboratory for HIVEGUARD.

Generates reproducible:
1. Sensor Fault Scenarios (ground truth generated by simulation)
2. Hypothetical Environmental & Colony Stress Scenarios (explicitly marked as hypothetical)
"""
from dataclasses import dataclass, asdict
import numpy as np
import pandas as pd


@dataclass
class SimulationScenarioConfig:
    scenario_category: str  # "sensor_fault" or "hypothetical_environmental"
    scenario_type: str
    channel: str
    start_index: int
    duration_steps: int
    severity: float
    random_seed: int
    description: str


def inject_sensor_fault(
    df: pd.DataFrame,
    channel: str = "temperature_C",
    fault_type: str = "isolated_spike",
    start_index: int = 100,
    duration: int = 1,
    severity: float = 12.0,
    seed: int = 42,
) -> tuple[pd.DataFrame, dict]:
    """Inject a controlled sensor fault into a copy of the dataset.
    
    Fault types:
    - isolated_spike: Single-step impulse jump
    - stuck_sensor: Freeze reading over duration
    - gradual_drift: Monotonic bias added over duration
    - gaussian_noise: Additive high-variance noise
    - missing_data: Replace values with NaN
    """
    rng = np.random.default_rng(seed)
    df_sim = df.copy()

    if channel not in df_sim.columns:
        raise ValueError(f"Channel '{channel}' not found in dataset columns: {list(df_sim.columns)}")

    n = len(df_sim)
    start_idx = max(0, min(start_index, n - 2))
    end_idx = min(start_idx + duration, n)

    # Initialize ground-truth fault mask
    fault_mask = np.zeros(n, dtype=bool)
    original_series = df_sim[channel].copy()
    vals = df_sim[channel].values.astype(float).copy()

    if fault_type == "isolated_spike":
        # Single or multi-step sharp spike that returns
        vals[start_idx:end_idx] += severity
        fault_mask[start_idx:end_idx] = True

    elif fault_type == "stuck_sensor":
        # Freeze at the start value
        freeze_val = vals[start_idx]
        vals[start_idx:end_idx] = freeze_val
        fault_mask[start_idx:end_idx] = True

    elif fault_type == "gradual_drift":
        # Linear slope drift
        drift_steps = end_idx - start_idx
        drift_ramp = np.linspace(0.0, severity, drift_steps)
        vals[start_idx:end_idx] += drift_ramp
        fault_mask[start_idx:end_idx] = True

    elif fault_type == "gaussian_noise":
        noise = rng.normal(loc=0.0, scale=abs(severity), size=(end_idx - start_idx))
        vals[start_idx:end_idx] += noise
        fault_mask[start_idx:end_idx] = True

    elif fault_type == "missing_data":
        vals[start_idx:end_idx] = np.nan
        fault_mask[start_idx:end_idx] = True

    else:
        raise ValueError(f"Unknown fault_type: {fault_type}")

    df_sim[f"{channel}_original"] = original_series
    df_sim[channel] = np.round(vals, 2)
    df_sim["injected_ground_truth_fault"] = fault_mask
    df_sim["simulation_scenario"] = f"sensor_fault:{fault_type}"

    config = {
        "scenario_category": "sensor_fault",
        "scenario_type": fault_type,
        "channel": channel,
        "start_index": int(start_idx),
        "duration_steps": int(end_idx - start_idx),
        "severity": float(severity),
        "random_seed": int(seed),
        "total_timesteps": n,
        "fault_timesteps": int(fault_mask.sum()),
        "description": f"Controlled {fault_type} fault injected on '{channel}' from step {start_idx} to {end_idx} (severity: {severity}).",
    }

    return df_sim, config


def inject_hypothetical_environmental_stress(
    df: pd.DataFrame,
    stress_type: str = "brood_chilling",
    start_index: int = 150,
    duration: int = 36,  # e.g., 36 steps * 15 min = 9 hours
    severity: float = 4.5,
    seed: int = 42,
) -> tuple[pd.DataFrame, dict]:
    """Inject a hypothetical colony stress scenario.
    
    Explicitly labeled as hypothetical research simulation.
    Scenarios:
    - brood_chilling: Progressive thermal depression with elevated humidity
    - acute_hyperthermia: High temperature spike
    - sensor_conflict: Temperature spikes while acoustic and humidity stay normal
    """
    df_sim = df.copy()
    n = len(df_sim)
    start_idx = max(0, min(start_index, n - 2))
    end_idx = min(start_idx + duration, n)
    stress_mask = np.zeros(n, dtype=bool)

    if "temperature_C" in df_sim.columns:
        t_vals = df_sim["temperature_C"].values.astype(float).copy()
        df_sim["temperature_C_original"] = df_sim["temperature_C"].copy()
    else:
        t_vals = np.full(n, 34.4)

    if "humidity_percent" in df_sim.columns:
        h_vals = df_sim["humidity_percent"].values.astype(float).copy()
        df_sim["humidity_percent_original"] = df_sim["humidity_percent"].copy()
    else:
        h_vals = np.full(n, 58.0)

    ramp_steps = end_idx - start_idx

    if stress_type == "brood_chilling":
        # Temperature drops smoothly, humidity rises
        t_drop = np.linspace(0.0, severity, ramp_steps)
        h_rise = np.linspace(0.0, severity * 2.5, ramp_steps)
        t_vals[start_idx:end_idx] -= t_drop
        h_vals[start_idx:end_idx] += h_rise
        stress_mask[start_idx:end_idx] = True

    elif stress_type == "acute_hyperthermia":
        t_rise = np.linspace(0.0, severity, ramp_steps)
        t_vals[start_idx:end_idx] += t_rise
        stress_mask[start_idx:end_idx] = True

    elif stress_type == "sensor_conflict":
        # Sudden unphysical jump in temperature only, humidity completely stable
        t_vals[start_idx:end_idx] += severity * 2.0
        stress_mask[start_idx:end_idx] = True

    if "temperature_C" in df_sim.columns:
        df_sim["temperature_C"] = np.round(t_vals, 2)
    if "humidity_percent" in df_sim.columns:
        df_sim["humidity_percent"] = np.round(h_vals, 2)

    df_sim["injected_ground_truth_stress"] = stress_mask
    df_sim["simulation_scenario"] = f"hypothetical_stress:{stress_type}"

    config = {
        "scenario_category": "hypothetical_environmental_stress",
        "scenario_type": stress_type,
        "start_index": int(start_idx),
        "duration_steps": int(end_idx - start_idx),
        "severity": float(severity),
        "random_seed": int(seed),
        "total_timesteps": n,
        "stress_timesteps": int(stress_mask.sum()),
        "description": f"Hypothetical {stress_type} simulated from step {start_idx} to {end_idx}. Not validated as confirmed clinical diagnosis.",
    }

    return df_sim, config
